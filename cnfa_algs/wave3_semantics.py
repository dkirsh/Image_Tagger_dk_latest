    def _load_canonical(self) -> Dict[str, Any]:
        if not os.path.exists(CANONICAL_ONTOLOGY_PATH):
            return {}
        with open(CANONICAL_ONTOLOGY_PATH, 'r') as f:
            return yaml.safe_load(f)

    def _load_dynamic_registry(self) -> List[Dict[str, Any]]:
        if not os.path.exists(DYNAMIC_REGISTRY_PATH):
            return []
        with open(DYNAMIC_REGISTRY_PATH, 'r') as f:
            try:
                return json.load(f)
            except json.JSONDecodeError:
                return []

    def get_full_vocabulary(self) -> List[str]:
        """
        Extracts all textual search terms from both the Canonical Dictionary and the Dynamic Registry.
        """
        vocab = []
        # Extract from Canonical
        for category, items in self.canonical_ontology.get("architectural_elements", {}).items():
            for item in items:
                vocab.extend(item.get("vlm_synonyms", []))
                
        # Extract from Dynamic Registry
